#!/usr/bin/env python3
"""Assemble contracts/openapi.yaml from the per-spec OpenAPI fragments.

Every file matching specs/<feature>/contracts/*.yaml is an OpenAPI 3.1 fragment. The features
included are listed, one spec directory per line, in contracts/features.txt (a feature is added
when its implementation lands, so the assembled contract only describes what the API serves).
``--all`` assembles every spec and reports every conflict, to preview later waves. This script:

* rewrites every cross-file ``$ref`` (``./core.yaml#/components/...`` or
  ``../../001-platform-foundation/contracts/core.yaml#/components/...``) to a local
  ``#/components/...`` ref, after checking that the target exists;
* merges components by name. Duplicates that are identical once documentation-only keys
  (description, summary, example, examples) are ignored are merged; anything else fails;
* merges paths. The same (path, method) defined twice fails; different methods on one path
  are combined;
* tags every operation with ``x-spec: <spec directory>`` so tests can tell which feature
  owns an operation.

Usage::

    python scripts/assemble_contracts.py           # write contracts/openapi.yaml
    python scripts/assemble_contracts.py --check   # exit 1 when the committed file is stale
    python scripts/assemble_contracts.py --all --dry-run   # report conflicts across all specs
"""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "contracts" / "openapi.yaml"
FEATURES = ROOT / "contracts" / "features.txt"
HTTP_METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}
DOC_KEYS = {"description", "summary", "example", "examples"}
HEADER = "# GENERATED by scripts/assemble_contracts.py from specs/*/contracts/*.yaml. Do not edit.\n"


class AssemblyError(Exception):
    pass


def _load(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise AssemblyError(f"{path}: not a mapping")
    return data


def _resolve_pointer(doc: dict[str, Any], pointer: str, where: str) -> Any:
    node: Any = doc
    for raw in pointer.lstrip("/").split("/"):
        part = raw.replace("~1", "/").replace("~0", "~")
        if not isinstance(node, dict) or part not in node:
            raise AssemblyError(f"{where}: unresolved ref target #{pointer}")
        node = node[part]
    return node


class Assembler:
    def __init__(self, files: list[Path]) -> None:
        self.files = files
        self.cache: dict[Path, dict[str, Any]] = {}
        self.paths: dict[str, dict[str, Any]] = {}
        self.path_origin: dict[tuple[str, str], Path] = {}
        self.components: dict[str, dict[str, Any]] = {}
        self.component_origin: dict[tuple[str, str], Path] = {}
        self.tags: list[str] = []
        self.errors: list[str] = []

    def doc(self, path: Path) -> dict[str, Any]:
        path = path.resolve()
        if path not in self.cache:
            if not path.exists():
                raise AssemblyError(f"referenced file does not exist: {path.relative_to(ROOT)}")
            self.cache[path] = _load(path)
        return self.cache[path]

    def rewrite(self, node: Any, source: Path) -> Any:
        if isinstance(node, dict):
            out: dict[str, Any] = {}
            for key, value in node.items():
                if key == "$ref" and isinstance(value, str):
                    out[key] = self._rewrite_ref(value, source)
                else:
                    out[key] = self.rewrite(value, source)
            return out
        if isinstance(node, list):
            return [self.rewrite(item, source) for item in node]
        return node

    def _rewrite_ref(self, ref: str, source: Path) -> str:
        file_part, _, pointer = ref.partition("#")
        target = (source.parent / file_part).resolve() if file_part else source.resolve()
        where = f"{source.relative_to(ROOT)} ($ref {ref})"
        if not pointer.startswith("/components/"):
            raise AssemblyError(f"{where}: only refs to components are supported")
        _resolve_pointer(self.doc(target), pointer, where)
        if file_part:
            # Pull the referenced component in even when its file is not a fragment we merge.
            parts = pointer.lstrip("/").split("/")
            if len(parts) == 3:
                self._add_component(parts[1], parts[2], self.doc(target)[parts[0]][parts[1]][parts[2]],
                                    target)
        return "#" + pointer

    def _add_component(self, kind: str, name: str, value: Any, source: Path) -> None:
        rewritten = self.rewrite(value, source)
        bucket = self.components.setdefault(kind, {})
        if name in bucket:
            if _strip_docs(bucket[name]) != _strip_docs(rewritten):
                first = self.component_origin[(kind, name)].relative_to(ROOT)
                self.errors.append(
                    f"conflicting component {kind}/{name}: {first} vs {source.relative_to(ROOT)}"
                )
                return
            if _doc_weight(rewritten) > _doc_weight(bucket[name]):
                bucket[name] = rewritten
            return
        bucket[name] = rewritten
        self.component_origin[(kind, name)] = source

    def run(self) -> dict[str, Any]:
        for path in self.files:
            source = path.resolve()
            spec_dir = path.parent.parent.name
            doc = self.doc(source)
            for kind, entries in (doc.get("components") or {}).items():
                for name, value in (entries or {}).items():
                    self._add_component(kind, name, value, source)
            for url, item in (doc.get("paths") or {}).items():
                item = self.rewrite(item, source)
                merged = self.paths.setdefault(url, {})
                for key, value in item.items():
                    if key in HTTP_METHODS:
                        if key in merged:
                            first = self.path_origin[(url, key)].relative_to(ROOT)
                            self.errors.append(
                                f"duplicate operation {key.upper()} {url}: {first} vs {path.relative_to(ROOT)}"
                            )
                            continue
                        value = dict(value)
                        value["x-spec"] = spec_dir
                        merged[key] = value
                        self.path_origin[(url, key)] = path
                        for tag in value.get("tags", []):
                            if tag not in self.tags:
                                self.tags.append(tag)
                    elif key in merged and _strip_docs(merged[key]) != _strip_docs(value):
                        self.errors.append(f"conflicting path-level '{key}' on {url} in {path}")
                    else:
                        merged[key] = value
        if self.errors:
            raise AssemblyError("\n  ".join(["contract conflicts:", *self.errors]))
        return self._document()

    def _document(self) -> dict[str, Any]:
        components = {
            kind: {name: self.components[kind][name] for name in sorted(self.components[kind])}
            for kind in sorted(self.components)
        }
        return {
            "openapi": "3.1.0",
            "info": {
                "title": "Callwright API",
                "version": "1.0.0",
                "description": "Assembled from the per-feature fragments in specs/*/contracts/.",
            },
            "servers": [{"url": "/v1"}],
            "tags": [{"name": tag} for tag in sorted(self.tags)],
            "paths": {url: self.paths[url] for url in sorted(self.paths)},
            "components": components,
        }


def _strip_docs(node: Any) -> Any:
    if isinstance(node, dict):
        return {k: _strip_docs(v) for k, v in node.items() if k not in DOC_KEYS}
    if isinstance(node, list):
        return [_strip_docs(v) for v in node]
    return node


def _doc_weight(node: Any) -> int:
    if isinstance(node, dict):
        return sum((1 if k in DOC_KEYS else 0) + _doc_weight(v) for k, v in node.items())
    if isinstance(node, list):
        return sum(_doc_weight(v) for v in node)
    return 0


def included_features(root: Path = ROOT) -> list[str]:
    manifest = root / "contracts" / "features.txt"
    lines = manifest.read_text(encoding="utf-8").splitlines() if manifest.exists() else []
    return [line.strip() for line in lines if line.strip() and not line.startswith("#")]


def fragment_files(root: Path = ROOT, features: list[str] | None = None) -> list[Path]:
    files = sorted(root.glob("specs/*/contracts/*.yaml"))
    if features is None:
        return files
    unknown = [f for f in features if not (root / "specs" / f / "contracts").is_dir()]
    if unknown:
        raise AssemblyError(f"contracts/features.txt names unknown specs: {', '.join(unknown)}")
    return [f for f in files if f.parent.parent.name in features]


def assemble(root: Path = ROOT, all_specs: bool = False) -> str:
    features = None if all_specs else included_features(root)
    document = Assembler(fragment_files(root, features)).run()
    body = yaml.safe_dump(copy.deepcopy(document), sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when contracts/openapi.yaml is stale")
    parser.add_argument("--all", action="store_true", help="assemble every spec, not only features.txt")
    parser.add_argument("--dry-run", action="store_true", help="assemble and validate without writing")
    args = parser.parse_args(argv)
    try:
        text = assemble(all_specs=args.all)
    except AssemblyError as exc:
        print(f"assemble_contracts: {exc}", file=sys.stderr)
        return 2
    if args.dry_run:
        print(f"assembled OK ({len(text.splitlines())} lines)")
        return 0
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("contracts/openapi.yaml is stale; run scripts/assemble_contracts.py", file=sys.stderr)
            return 1
        print("contracts/openapi.yaml is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
