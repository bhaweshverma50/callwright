"""Apply one logo concept to the web app.

    uv run --with fonttools --with brotli python apps/web/scripts/brand/apply_concept.py <concept> [--out DIR]

<concept> is one of: handoff, dovetail, thread, two-voices.

Without --out it writes into apps/web (the real apply); with --out it writes the same tree under
DIR so the result can be reviewed first. It produces:

  public/favicon.svg, public/favicon.ico (16, 32, 48), public/apple-touch-icon.png (180),
  public/icon-192.png, public/icon-512.png, public/icon-maskable-512.png, public/og-image.png
  (1200x630), public/site.webmanifest, public/brand/{symbol,symbol-dark,lockup-light,lockup-dark,mono}.svg
  src/components/logo-data.generated.ts  symbol and lockup art, colours as --logo-* tokens
  src/components/Logo.tsx                from templates/Logo.tsx (same props as before, so the
                                         Sidebar, PublicLayout, AuthLayout and gallery usages keep
                                         working unchanged)
  src/index.css                          the brand:logo block from templates/logo.css (replaced in
                                         place when it is already there)
  index.html                             apple-touch-icon, manifest, theme-color and Open Graph tags

PNG rendering and the .ico use scripts/brand/rasterize.mjs (Playwright Chromium).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import tempfile

from marks import CONCEPTS, COBALT, INK, INK_DEEP, PAPER, PINK, VIOLET, f
from type import Face, set_line
from wordmarks import lockup

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.normpath(os.path.join(HERE, "..", ".."))

THEMED = {INK: "var(--logo-ink)", COBALT: "var(--logo-cobalt)", VIOLET: "var(--logo-violet)", PINK: "var(--logo-pink)"}
TAGLINE = "Build, run and keep improving AI voice agents."


def themed(markup: str) -> str:
    for hexv, var in THEMED.items():
        markup = markup.replace(f'"{hexv}"', f'"{var}"')
    return markup


def svg_doc(inner: str, w: float, h: float, extra: str = "") -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {f(w)} {f(h)}" width="{f(w)}" height="{f(h)}"{extra}>{inner}</svg>\n'


def icon_bg(c) -> str:
    # Dovetail's upper block is ink, so its full-bleed icons sit on paper instead.
    return PAPER if c.key == "dovetail" else INK


def full_bleed(c, scale: float) -> str:
    """Square icon (apple-touch, maskable): solid background, the tile mark centred at `scale`."""
    o = 24 * (1 - scale)
    return svg_doc(
        f'<rect width="48" height="48" fill="{icon_bg(c)}"/><g transform="translate({f(o)} {f(o)}) scale({f(scale)})">{c.mark("tile", "i")}</g>',
        48,
        48,
    )


def og_image(c) -> str:
    W, H = 1200, 630
    inner, lw, lh = lockup(c.key, "o", "dark", 48)
    k = 120 / 48
    face = Face("geist", 400, 34)
    tag = set_line(face, TAGLINE, 0, 0)
    tag_paths = "".join(f'<path d="{d}"/>' for d in tag.paths)
    return svg_doc(
        f'<defs><radialGradient id="g" cx="0.82" cy="0.18" r="0.75"><stop offset="0" stop-color="{VIOLET}" stop-opacity="0.32"/>'
        f'<stop offset="1" stop-color="{VIOLET}" stop-opacity="0"/></radialGradient>'
        f'<radialGradient id="h" cx="0.1" cy="0.95" r="0.6"><stop offset="0" stop-color="{COBALT}" stop-opacity="0.28"/>'
        f'<stop offset="1" stop-color="{COBALT}" stop-opacity="0"/></radialGradient></defs>'
        f'<rect width="{W}" height="{H}" fill="{INK_DEEP}"/><rect width="{W}" height="{H}" fill="url(#g)"/><rect width="{W}" height="{H}" fill="url(#h)"/>'
        f'<g transform="translate(96 210) scale({f(k)})">{inner}</g>'
        f'<g transform="translate(100 420)" fill="#B7BBDA">{tag_paths}</g>',
        W,
        H,
    )


def generated_ts(c) -> str:
    sym = themed(c.mark("light", "__UID__"))
    sym_mono = c.mark("mono", "__UID__")
    lk, lw, lh = lockup(c.key, "__UID__", "light", 48)
    lk_mono, _, _ = lockup(c.key, "__UID__", "mono", 48)

    def art(name: str, markup: str, w: float, h: float) -> str:
        return f"export const {name}: LogoArt = {{ w: {f(w)}, h: {f(h)}, markup: {json.dumps(markup)} }};\n"

    return (
        f"// Generated by scripts/brand/apply_concept.py (concept: {c.key}). Do not edit by hand.\n"
        "// Element ids carry a __UID__ placeholder that Logo replaces with useId().\n\n"
        "export type LogoArt = { w: number; h: number; markup: string };\n\n"
        f'export const LOGO_CONCEPT = "{c.key}";\n\n'
        + art("SYMBOL", sym, 48, 48)
        + art("SYMBOL_MONO", sym_mono, 48, 48)
        + art("LOCKUP", themed(lk), lw, lh)
        + art("LOCKUP_MONO", lk_mono, lw, lh)
    )


HEAD_TAGS = """    <link rel="icon" href="/favicon.ico" sizes="48x48" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
    <link rel="manifest" href="/site.webmanifest" />
    <meta name="theme-color" content="#F4F5FA" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#0E1030" media="(prefers-color-scheme: dark)" />
    <meta property="og:title" content="Callwright" />
    <meta property="og:description" content="Build, run and keep improving AI voice agents." />
    <meta property="og:image" content="/og-image.png" />
    <meta name="twitter:card" content="summary_large_image" />
"""


def patch_index_html(src: str) -> str:
    # Drop any icon, manifest, theme-color and og/twitter tags, then add ours after the description.
    src = re.sub(r'\n\s*<link rel="(icon|apple-touch-icon|manifest)"[^>]*/>', "", src)
    src = re.sub(r'\n\s*<meta (name="theme-color"|property="og:[^"]+"|name="twitter:[^"]+")[^>]*/>', "", src)
    return re.sub(r'(<meta name="description"[^>]*/>\n)', lambda m: m.group(1) + HEAD_TAGS, src, count=1)


def patch_index_css(src: str, block: str) -> str:
    pat = re.compile(r"/\* brand:logo:start.*?/\* brand:logo:end \*/\n?", re.S)
    if pat.search(src):
        return pat.sub(block, src)
    return src.rstrip("\n") + "\n\n" + block


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("concept", choices=[c.key for c in CONCEPTS])
    ap.add_argument("--out", help="write the tree here instead of apps/web")
    args = ap.parse_args()
    c = next(x for x in CONCEPTS if x.key == args.concept)
    root = os.path.abspath(args.out) if args.out else WEB
    pub = os.path.join(root, "public")
    comp = os.path.join(root, "src", "components")
    for d in (pub, os.path.join(pub, "brand"), comp):
        os.makedirs(d, exist_ok=True)

    def write(path: str, body: str) -> None:
        with open(path, "w") as fh:
            fh.write(body)

    # Vector assets
    write(os.path.join(pub, "favicon.svg"), svg_doc(c.mark("tile", "f"), 48, 48))
    write(os.path.join(pub, "brand", "symbol.svg"), svg_doc(c.mark("light", "s"), 48, 48))
    write(os.path.join(pub, "brand", "symbol-dark.svg"), svg_doc(c.mark("dark", "s"), 48, 48))
    for mode, name in (("light", "lockup-light.svg"), ("dark", "lockup-dark.svg"), ("mono", "mono.svg")):
        inner, w, h = lockup(c.key, "l", mode, 48)
        write(os.path.join(pub, "brand", name), svg_doc(inner, w, h, f' color="{INK}"' if mode == "mono" else ""))
    write(
        os.path.join(pub, "site.webmanifest"),
        json.dumps(
            {
                "name": "Callwright",
                "short_name": "Callwright",
                "icons": [
                    {"src": "/icon-192.png", "sizes": "192x192", "type": "image/png"},
                    {"src": "/icon-512.png", "sizes": "512x512", "type": "image/png"},
                    {"src": "/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
                ],
                "theme_color": "#0E1030",
                "background_color": "#F4F5FA",
                "display": "standalone",
                "start_url": "/",
            },
            indent=2,
        )
        + "\n",
    )

    # Raster assets
    tmp = tempfile.mkdtemp(prefix="cw-brand-")
    srcs = {
        "tile": svg_doc(c.mark("tile", "t"), 48, 48),
        "apple": full_bleed(c, 0.78),
        "maskable": full_bleed(c, 0.62),  # mark inside the 80 percent safe circle
        "og": og_image(c),
    }
    for k, body in srcs.items():
        write(os.path.join(tmp, f"{k}.svg"), body)
    png = lambda k, out, w, h=None, transparent=True: {  # noqa: E731
        "svg": os.path.join(tmp, f"{k}.svg"), "out": out, "w": w, "h": h or w, "transparent": transparent
    }
    ico = [os.path.join(tmp, f"ico-{s}.png") for s in (16, 32, 48)]
    jobs = {
        "png": [png("tile", p, s) for p, s in zip(ico, (16, 32, 48))]
        + [
            png("apple", os.path.join(pub, "apple-touch-icon.png"), 180, transparent=False),
            png("tile", os.path.join(pub, "icon-192.png"), 192),
            png("tile", os.path.join(pub, "icon-512.png"), 512),
            png("maskable", os.path.join(pub, "icon-maskable-512.png"), 512, transparent=False),
            png("og", os.path.join(pub, "og-image.png"), 1200, 630, transparent=False),
        ],
        "ico": {"pngs": ico, "out": os.path.join(pub, "favicon.ico")},
    }
    write(os.path.join(tmp, "jobs.json"), json.dumps(jobs))
    subprocess.run(["node", os.path.join(HERE, "rasterize.mjs"), os.path.join(tmp, "jobs.json")], check=True)
    shutil.rmtree(tmp)

    # Component, tokens and head tags
    write(os.path.join(comp, "logo-data.generated.ts"), generated_ts(c))
    shutil.copyfile(os.path.join(HERE, "templates", "Logo.tsx"), os.path.join(comp, "Logo.tsx"))
    with open(os.path.join(HERE, "templates", "logo.css")) as fh:
        block = fh.read()
    for rel, patch in (("src/index.css", lambda s: patch_index_css(s, block)), ("index.html", patch_index_html)):
        src_path = os.path.join(WEB, rel)
        dst_path = os.path.join(root, rel)
        with open(src_path) as fh:
            body = patch(fh.read())
        os.makedirs(os.path.dirname(dst_path), exist_ok=True)
        write(dst_path, body)
    print(f"applied {c.key} to {root}")


if __name__ == "__main__":
    main()
